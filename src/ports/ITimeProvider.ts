/**
 * Порт времени. Реализация — performance.now()-адаптер.
 * Позволяет тестировать игровой цикл без реального времени.
 */
export interface ITimeProvider {
  /** Текущее время в секундах. */
  now(): number;
  /** Delta между кадрами (секунды). */
  delta(): number;
  /** Отметить начало кадра (пересчитать delta). */
  markFrame(): void;
}
