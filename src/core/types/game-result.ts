/** Результат прохождения уровня (диалог `lvl_completed`). */
export interface GameResult {
  moves: number;
  time: number; // секунды
  completed: boolean;
  /** Сколько раз игрок пользовался подсказкой на этом прохождении. */
  hints: number;
  /** Минимальное число ходов, за которое уровень проходится. */
  minMoves: number;
  /** Звёзды за прохождение: 3 — почти идеально, 2 — в пределах допуска, 1 — остальное. */
  stars: number;
}

/**
 * Лучший результат прохождения уровня: лежит в сейве, из него берутся звёзды
 * на карточке уровня в меню выбора.
 */
export interface LevelRecord {
  /** Ходы в лучшем прохождении. */
  moves: number;
  /** Сколько подсказок было использовано в этом прохождении. */
  hints: number;
  /** Время прохождения в секундах. */
  time: number;
  /** Звёзды, полученные за этот заход. */
  stars: number;
}

/**
 * Звёзды за прохождение с учётом подсказок.
 *
 * Оценка идёт по «приведённым» ходам: каждый просмотр подсказки приравнивается
 * к части идеального решения (`hintCost`), потому что подсказка выдаёт готовый
 * следующий ход — без штрафа уровень можно пройти по подсказкам за минимум
 * ходов и получить три звезды, ничего не решив самому.
 *
 * Ошибки прощаются в долях от минимума, а не поштучно: на длинном уровне
 * лишний ход — мелочь, на коротком он уже заметен.
 *
 * Ступени:
 * - 3 звезды — запас не больше 10% минимума (хотя бы один ход): найти
 *   решение и один раз ошибиться — нормальная игра, а не брак;
 * - 2 звезды — запас до 60% минимума (при 10 ходах — до 16): уровень пройден
 *   осмысленно, но с блужданием;
 * - иначе 1 звезда: уровень всё равно пройден.
 *
 * Любая подсказка выводит из трёх звёзд: она стоит 40% минимума (но не
 * меньше двух ходов), то есть больше допуска на первую ступень.
 *
 * Минимум ходов неизвестен (решатель не обошёл граф) — оценивать не по чему,
 * 3 звезды.
 */
export function starsForResult(moves: number, minMoves: number, hints = 0): number {
  if (minMoves <= 0) return 3;
  // Подсказка выдаёт готовый ход, поэтому стоит четверть идеального решения
  // (но не меньше двух ходов): без штрафа уровень проходится по подсказкам за
  // минимум ходов и получает три звезды.
  const hintCost = Math.max(2, Math.round(minMoves * 0.4));
  const effective = moves + Math.max(0, hints) * hintCost;

  // Допуски в долях минимума; нижние границы не дают ступеням схлопнуться
  // на коротких уровнях (там 10% — это «ни одного хода»).
  const perfectSlack = Math.max(1, Math.round(minMoves * 0.1));
  const goodSlack = Math.max(perfectSlack + 1, Math.round(minMoves * 0.6));

  if (effective <= minMoves + perfectSlack) return 3;
  if (effective <= minMoves + goodSlack) return 2;
  return 1;
}
