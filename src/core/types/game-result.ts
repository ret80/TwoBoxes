/** Результат прохождения уровня (диалог `lvl_completed`). */
export interface GameResult {
  moves: number;
  time: number; // секунды
  completed: boolean;
  /** Сколько раз игрок пользовался подсказкой на этом прохождении. */
  hints: number;
  /** Минимальное число ходов, за которое уровень проходится. */
  minMoves: number;
  /** Звёзды за прохождение: 3 — идеально, 2 — близко к минимуму, 1 — остальное. */
  stars: number;
}

/**
 * Звёзды за прохождение с учётом подсказок.
 *
 * Оценка идёт по «приведённым» ходам: каждый просмотр подсказки приравнивается
 * к части идеального решения (`hintCost`), потому что подсказка выдаёт готовый
 * следующий ход — без штрафа уровень можно пройти по подсказкам за минимум
 * ходов и получить три звезды, ничего не решив самому.
 *
 * Ступени (при `hints = 0` совпадают с прежним правилом за ходы):
 * - 3 звезды — идеальное прохождение строго по минимуму и без подсказок
 *   (любая подсказка уже выводит из этой ступени);
 * - 2 звезды — запас не больше половины минимума (минимум один запасной ход,
 *   иначе одна ошибка на коротком уровне сразу роняла бы оценку);
 * - иначе 1 звезда: уровень всё равно пройден.
 *
 * Минимум ходов неизвестен (решатель не обошёл граф) — оценивать не по чему,
 * 3 звезды.
 */
export function starsForResult(moves: number, minMoves: number, hints = 0): number {
  if (minMoves <= 0) return 3;
  // Подсказка стоит половину идеального решения (но не меньше двух ходов):
  // на длинном уровне она экономит больше, чем на коротком.
  const hintCost = Math.max(2, Math.round(minMoves * 0.5));
  const effective = moves + Math.max(0, hints) * hintCost;
  if (effective <= minMoves) return 3;
  const slack = Math.max(1, Math.ceil(minMoves * 0.5));
  if (effective <= minMoves + slack) return 2;
  return 1;
}
